// Deterministic fuel log generator so every vehicle has a believable history
function fuelLog(
  prefix: string,
  startOdo: number,
  pricePerUnit: number,
  unitsPerFill: number,
  station: string
): FuelEntry[] {
  const dates = ['2026-09-22', '2026-09-12', '2026-09-01', '2026-08-19', '2026-08-06', '2026-07-24'];
  return dates.map((date, i) => {
    const litres = Math.round(unitsPerFill * (0.8 + ((i * 37) % 30) / 100));
    return {
      id: `${prefix}-F${i + 1}`,
      date,
      litres,
      cost: Math.round(litres * pricePerUnit),
      odometerKm: startOdo - i * 640,
      station,
    };
  });
}

